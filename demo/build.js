#!/usr/bin/env node
// Builds demo.html (repo root) from ministering_tool.html: the same app, with
// the Firebase SDK swapped for demo/fake-firebase.js and the invented ward in
// demo/demo-data.js, plus a banner. Run after any change to the app:
//   node demo/build.js
// demo.html talks to no server: no Firebase project, no sign-in service, no
// push. It never sees real member data.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
let html = fs.readFileSync(path.join(root, 'ministering_tool.html'), 'utf8');

function swap(from, to, label) {
  if (!html.includes(from)) throw new Error('demo build: could not find ' + label);
  html = html.replace(from, to);
}

// 1. Firebase SDK → the in-browser stand-in (data first, so it can seed).
// Inlined, so demo.html is one self-contained file that can be emailed or opened from disk.
const inline = f => '<script>\n' + fs.readFileSync(path.join(__dirname, f), 'utf8').replace(/<\/script/gi, '<\\/script') + '\n</script>';
let found = false;
html = html.replace(/<script src="vendor\/firebase-[^"]+"><\/script>/, () => { found = true; return inline('demo-data.js') + '\n' + inline('fake-firebase.js'); });
if (!found) throw new Error('demo build: Firebase script tag not found');

// 2. Never paused, never installs, no service worker, no push key.
html = html.replace('const TOOL_PAUSED = true;', 'const TOOL_PAUSED = false;');   // if the pause switch is there
swap("navigator.serviceWorker.register('sw.js')", "Promise.resolve()", 'service worker registration');
html = html.replace(/<link rel="manifest"[^>]*>\s*/, '');
html = html.replace(/const VAPID_PUBLIC_KEY = '[^']*';/, "const VAPID_PUBLIC_KEY = '';");
html = html.replace(/<title>([^<]*)<\/title>/, (m, t) => `<title>DEMO · ${t}</title>`);

// 3. The demo banner: what this is, who you're viewing as, reset.
const bar = `
<div id="demo-bar" role="note">
  <div class="demo-msg"><strong>DEMO</strong> · An invented ward: every name, address, phone number and note is made up.<span class="demo-long">
    Nothing is sent anywhere; changes stay in this browser tab.</span></div>
  <div class="demo-ctl">
    <label for="demo-as">View as</label>
    <select id="demo-as"></select>
    <button type="button" id="demo-reset">Reset demo</button>
  </div>
</div>
<style>
  #demo-bar { position: sticky; top: 0; z-index: 10000; display: flex; flex-wrap: wrap; gap: 6px 14px; align-items: center;
    justify-content: space-between; padding: 8px 16px; background: #5b2a86; color: #fff; font: 14px/1.35 system-ui, sans-serif; }
  #demo-bar .demo-ctl { display: flex; gap: 8px; align-items: center; }
  #demo-bar select, #demo-bar button { font: inherit; padding: 4px 8px; border-radius: 6px; border: 0; }
  #demo-bar button { background: #fff; color: #5b2a86; font-weight: 600; cursor: pointer; }
  @media (max-width: 640px) {
    #demo-bar { position: static; padding: 6px 12px; font-size: 13px; }
    #demo-bar .demo-long { display: none; }
    #demo-bar select { max-width: 60vw; }
  }
</style>
<script>
(function () {
  var sel = document.getElementById('demo-as');
  var roleLabel = { eq: 'Elders quorum', rs: 'Relief Society', bishopric: 'Bishopric', council: 'Ward council' };
  var cur = window.DEMO.currentUid();
  window.DEMO.users().forEach(function (u) {
    var o = document.createElement('option');
    o.value = u.uid;
    o.textContent = u.firstName + ' ' + u.lastName + ' (' + (u.admin ? 'admin' : roleLabel[u.role] || 'ward council') + ')';
    if (u.uid === cur) o.selected = true;
    sel.appendChild(o);
  });
  var none = document.createElement('option'); none.value = ''; none.textContent = 'Signed out';
  if (!cur) none.selected = true;
  sel.appendChild(none);
  sel.addEventListener('change', function () { window.DEMO.viewAs(sel.value); });
  document.getElementById('demo-reset').addEventListener('click', function () {
    if (confirm('Put the demo ward back the way it started? Your changes in this tab will be lost.')) window.DEMO.reset();
  });
})();
</script>
`;
html = html.replace(/<body([^>]*)>/, (m) => m + bar);
if (!html.includes('id="demo-bar"')) throw new Error('demo build: <body> not found');

const out = html.replace(/^(<!DOCTYPE html>\s*)/i, '$1<!-- GENERATED by demo/build.js from ministering_tool.html. Do not edit; rebuild instead. -->\n');
fs.writeFileSync(path.join(root, 'demo.html'), out);
console.log('wrote demo.html (' + Math.round(out.length / 1024) + ' KB)');
